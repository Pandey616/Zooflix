const accessedAt = "2026-10-17";

function adw(scientificName: string, slug: string): AnimalReference {
  return {
    title: `Animal Diversity Web: ${scientificName}`,
    url: `https://animaldiversity.org/accounts/${slug}/`,
    publisher: "University of Michigan Museum of Zoology",
    accessedAt,
    sourceType: "species-account",
    supports: [
      "taxonomy",
      "description",
      "habitat",
      "distribution",
      "diet",
      "physicalCharacteristics",
      "behavior",
      "lifespan",
      "reproduction",
      "ecologicalRole",
      "threats",
      "facts",
    ],
  };
}

function commonsImage(
  filename: string,
  creator: string,
  license: string,
  licenseUrl: string,
  attributionText = creator,
  licenseNotes?: readonly string[],
): Readonly<{ imageSrc: string; imageAttribution: ImageAttribution }> {
  return {
    imageSrc: `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(filename)}?width=1200`,
    imageAttribution: {
      creator,
      sourceUrl: `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(filename)}`,
      license,
      licenseUrl,
      attributionText,
      verifiedAt: accessedAt,
      licenseNotes: licenseNotes ?? defaultLicenseNotes(license),
    },
  };
}

function defaultLicenseNotes(license: string): readonly string[] {
  if (license.includes("BY-SA")) {
    return ["Attribution is required; share-alike applies to adaptations."];
  }

  if (license.includes("BY")) {
    return ["Attribution is required; link to the licence and note changes if applicable."];
  }

  if (license.includes("CC0")) {
    return ["The Commons page marks this work as CC0; creator information is retained for credit."];
  }

  return ["The Commons page marks this file as public domain."];
}

function claimReview(
  status: AnimalClaimReview["status"],
  source: AnimalReference,
  note?: string,
): AnimalClaimReview {
  return {
    status,
    referenceUrls: [source.url],
    reviewedAt: accessedAt,
    note,
  };
}

function provenance(
  source: AnimalReference,
  overrides: Readonly<Record<string, AnimalClaimReview>> = {},
): AnimalProvenance {
  const claimReviews = {
    taxonomy: claimReview("verified", source),
    habitat: claimReview("verified", source),
    distribution: claimReview("verified", source),
    diet: claimReview("verified", source),
    physicalCharacteristics: claimReview("verified", source),
    behavior: claimReview("verified", source),
    lifespan: claimReview("verified", source),
    reproduction: claimReview("verified", source),
    description: claimReview(
      "partially-supported",
      source,
      "Editorial synthesis based on the inspected species account; not a direct quotation.",
    ),
    shortDescription: claimReview(
      "partially-supported",
      source,
      "Editorial synthesis based on the inspected species account; not a direct quotation.",
    ),
    ecologicalRole: claimReview(
      "partially-supported",
      source,
      "The account supports the ecological context; this wording is an editorial summary.",
    ),
    threats: claimReview(
      "partially-supported",
      source,
      "Threat wording is an editorial summary and requires a dedicated conservation source for current status.",
    ),
    facts: claimReview(
      "partially-supported",
      source,
      "Facts are paraphrased from relevant account sections and are not direct quotations.",
    ),
    conservationAssessment: claimReview(
      "unable-to-verify",
      source,
      "No canonical current assessment with verifiable date and taxonomic scope was incorporated.",
    ),
    ...overrides,
  };

  return {
    primarySource: source,
    verifiedAt: accessedAt,
    claimReviews,
    uncertainFields: [
      ...(claimReviews.conservationAssessment.status === "verified" ? [] : ["conservationAssessment"]),
      "fieldLevelScientificReview",
    ],
  };
}

